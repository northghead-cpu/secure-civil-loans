import { createRequire, stripTypeScriptTypes } from 'node:module';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const require=createRequire(new URL('../supabase/tests/edge/package.json',import.meta.url));
const pdf=require('pdf-lib'),jpeg=require('jpeg-js'),{PNG}=require('pngjs');
const source=stripTypeScriptTypes(await fs.readFile(new URL('../supabase/functions/upload-kyc-document/validate.ts',import.meta.url),'utf8'),{mode:'transform'}).replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
class RequestError extends Error {constructor(status,code){super(code);this.status=status;this.code=code;}}
const validate=new Function('PDFDocument','PDFDict','PDFArray','PDFName','PDFRef','jpeg','PNG','Buffer','RequestError',source+';return validateDocument;')(pdf.PDFDocument,pdf.PDFDict,pdf.PDFArray,pdf.PDFName,pdf.PDFRef,jpeg,PNG,Buffer,RequestError);
const valid=await pdf.PDFDocument.create();valid.addPage();const bytes=await valid.save();
assert.equal((await validate(bytes,'application/pdf')).extension,'pdf');
for(const bad of ['plain text labelled PDF','%PDF-1.7\nnot a document\n%%EOF'])await assert.rejects(validate(new TextEncoder().encode(bad),'application/pdf'),e=>e.status===422);
const active=await pdf.PDFDocument.create();active.addPage();active.catalog.set(pdf.PDFName.of('OpenAction'),active.context.obj({S:'JavaScript',JS:pdf.PDFString.of('harmless_test_marker')}));
await assert.rejects(validate(await active.save(),'application/pdf'),e=>e.status===422);
console.log('PASS: a parsed PDF is accepted; text, forged signature and active PDF content are rejected');
const png=PNG.sync.write({width:1,height:1,data:Buffer.from([20,40,60,255])});
assert.equal((await validate(png,'image/png')).extension,'png');
const broken=Buffer.from(png);broken[broken.length-5]^=1;
await assert.rejects(validate(broken,'image/png'),e=>e.status===422);
const huge=Buffer.from(png);huge.writeUInt32BE(100000,16);
await assert.rejects(validate(huge,'image/png'),e=>e.status===422);
await assert.rejects(validate(png,'application/pdf'),e=>e.status===422);
await assert.rejects(validate(Buffer.concat([png,Buffer.from('trailing payload')]),'image/png'),e=>e.status===422);
await assert.rejects(validate(Buffer.concat([png.slice(0,33),png.slice(8)]),'image/png'),e=>e.status===422);
console.log('PASS: PNG is parsed and normalized; CRC corruption, excess dimensions and MIME mismatch are rejected');
const jpg=jpeg.encode({width:1,height:1,data:Buffer.from([10,20,30,255]),comments:['synthetic metadata marker']},90).data;
const clean=await validate(jpg,'image/jpeg');
assert.equal(clean.extension,'jpg');assert.ok(!Buffer.from(clean.bytes).includes(Buffer.from('synthetic metadata marker')));
await assert.rejects(validate(jpg.slice(0,-2),'image/jpeg'),e=>e.status===422);
console.log('PASS: JPEG is decoded and normalized without comments; truncation is rejected');
